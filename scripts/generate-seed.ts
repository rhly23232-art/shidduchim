/**
 * Generates supabase/seed.sql from src/data/seedData.ts.
 * Run: node scripts/generate-seed.ts
 * Creates a demo matchmaker account (demo@shidduchim.local / shidduch123) and its 20 candidates.
 */
import { writeFileSync } from 'node:fs'
import { SEED_CANDIDATES } from '../src/data/seedData.ts'
import { gregorianToHebrew } from '../src/lib/hebrewDate.ts'

const DEMO_USER_ID = '11111111-1111-4111-8111-111111111111'
const DEMO_EMAIL = 'demo@shidduchim.local'
const DEMO_PASSWORD = 'shidduch123'

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

const lines: string[] = []
lines.push('-- AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.')
lines.push(`-- Demo matchmaker: ${DEMO_EMAIL} / ${DEMO_PASSWORD}`)
lines.push('')
lines.push(`insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values (
  '00000000-0000-0000-0000-000000000000', '${DEMO_USER_ID}', 'authenticated', 'authenticated',
  '${DEMO_EMAIL}', extensions.crypt('${DEMO_PASSWORD}', extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{"full_name":"שדכן הדגמה"}', now(), now(),
  '', '', '', ''
) on conflict (id) do nothing;`)
lines.push('')
lines.push(`insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (
  '${DEMO_USER_ID}', '${DEMO_USER_ID}', '${DEMO_USER_ID}',
  '{"sub":"${DEMO_USER_ID}","email":"${DEMO_EMAIL}","email_verified":true}', 'email', now(), now(), now()
) on conflict do nothing;`)
lines.push('')

SEED_CANDIDATES.forEach((s, i) => {
  const c = s.candidate
  const id = `22222222-2222-4222-8222-${String(i + 1).padStart(12, '0')}`
  const cols: Record<string, unknown> = {
    id,
    owner_id: DEMO_USER_ID,
    gender: c.gender,
    first_name: c.first_name,
    last_name: c.last_name,
    birth_date: c.birth_date,
    hebrew_birth_date: gregorianToHebrew(c.birth_date),
    city: c.city,
    region: c.region,
    country_of_origin: c.country_of_origin,
    community: c.community,
    chassidut: c.chassidut,
    height_cm: c.height_cm,
    appearance: c.appearance,
    institution: c.institution,
    institution_type: c.institution_type,
    occupation: c.occupation,
    degree: c.degree,
    future_plans: c.future_plans,
    character_description: c.character_description,
    desired_home_style: c.desired_home_style,
    special_requirements: c.special_requirements,
    general_notes: c.general_notes,
    status: c.status,
  }
  const names = [...Object.keys(cols), 'education_history']
  const values = [...Object.values(cols).map(q), `${q(JSON.stringify(c.education_history))}::jsonb`]
  lines.push(`-- ${c.first_name} ${c.last_name}`)
  lines.push(`insert into public.candidates (${names.join(', ')})\nvalues (${values.join(', ')});`)
  const f = s.family
  lines.push(
    `insert into public.family_details (candidate_id, father_name, father_occupation, mother_name, mother_occupation, mother_maiden_name, lineage, siblings_count, birth_order)\nvalues (${[
      id,
      f.father_name,
      f.father_occupation,
      f.mother_name,
      f.mother_occupation,
      f.mother_maiden_name,
      f.lineage,
      f.siblings_count,
      f.birth_order,
    ]
      .map(q)
      .join(', ')});`,
  )
  s.in_laws.forEach((l, j) => {
    lines.push(
      `insert into public.in_laws (candidate_id, relation, full_name, details, sort_order) values (${[
        id,
        l.relation,
        l.full_name,
        l.details,
        j,
      ]
        .map(q)
        .join(', ')});`,
    )
  })
  lines.push('')
})

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'))
console.log(`seed.sql written: ${SEED_CANDIDATES.length} candidates`)
