// End-to-end suite — run through tests/e2e/run.cjs (see docs/TESTING.md).
// Destructive: wipes the signed-in account's data. Keep it last in the run.
const { login, base, axeSrc } = require('./helpers.cjs')
const { chromium } = require('playwright')
let fails = 0
const ok = (c, s) => { console.log(c ? '✓' : '✗', s); if (!c) fails++ }
;(async () => {
  const b = await chromium.launch()
  const page = await (await b.newContext({ viewport: { width: 1280, height: 860 } })).newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const axe = async (label, sel) => {
    await page.addScriptTag({ content: axeSrc })
    const r = await page.evaluate(async (s) => await window.axe.run(s || document, { runOnly: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] }), sel)
    ok(r.violations.length === 0, `axe [${label}] ${r.violations.length}`)
    for (const v of r.violations) console.log('   -', v.id, v.nodes[0]?.target.join(' '))
  }
  await login(page)
  await page.getByRole('button', { name: 'תפריט משתמש' }).click()
  await page.getByRole('menuitem', { name: 'תמיכה ועזרה' }).click()
  await page.getByRole('button', { name: /ניהול החשבון/ }).click()
  await page.waitForSelector('text=אזור מחיקה')
  ok((await page.locator('main').innerText()).includes('demo@shidduchim.local'), 'account page shows the account')
  await axe('account page')

  // ---- wipe all data
  await page.getByRole('button', { name: 'מחיקת כל הנתונים' }).click()
  const dlg = page.getByRole('dialog')
  const submit = dlg.getByRole('button', { name: 'מחיקת כל הנתונים' })
  ok(await submit.isDisabled(), 'confirm disabled until the word and password are typed')
  await axe('confirm dialog', '[role=dialog]')
  await dlg.getByLabel(/הקלידו/).fill('מחיקה')
  await dlg.getByLabel('סיסמה').fill('wrong-password')
  await submit.click()
  await page.waitForTimeout(800)
  ok((await dlg.innerText()).includes('הסיסמה שגויה'), 'wrong password is refused')
  await dlg.getByLabel('סיסמה').fill('shidduch123')
  await submit.click()
  await page.waitForSelector('text=כל הנתונים נמחקו', { timeout: 20000 })
  await page.goto(base + '/candidates?tab=all')
  await page.waitForTimeout(1200)
  const mainText = await page.locator('main').innerText()
  ok(!(await page.locator('tbody tr').count()) && mainText.includes('עדיין אין מועמדים במאגר'), 'candidates table is empty after the wipe: ' + mainText.split('\n')[0])
  await page.goto(base + '/ideas'); await page.waitForTimeout(800)
  ok(!(await page.locator('main li').count()), 'ideas are empty after the wipe')

  // ---- delete an account (a fresh one)
  await page.getByRole('button', { name: 'תפריט משתמש' }).click()
  await page.getByRole('menuitem', { name: 'יציאה' }).click()
  await page.waitForSelector('input[type=email]')
  await page.getByRole('button', { name: /להרשמה/ }).click()
  const email = `erase-${Date.now()}@example.com`
  await page.getByLabel('שם מלא').fill('חשבון למחיקה')
  await page.getByLabel('דואר אלקטרוני').fill(email)
  await page.getByLabel(/^סיסמה/).first().fill('Erase-12345')
  const confirmPw = page.getByLabel(/אימות סיסמה/)
  if (await confirmPw.count()) await confirmPw.fill('Erase-12345')
  await page.locator('button[type=submit]').click()
  await page.getByRole('button', { name: 'תפריט משתמש' }).waitFor({ timeout: 15000 })
  await page.goto(base + '/account'); await page.waitForSelector('text=אזור מחיקה')
  await page.getByRole('button', { name: 'מחיקת החשבון' }).click()
  await page.getByRole('dialog').getByLabel(/הקלידו/).fill('מחיקה')
  await page.getByRole('dialog').getByLabel('סיסמה').fill('Erase-12345')
  await page.getByRole('dialog').getByRole('button', { name: 'מחיקת החשבון' }).click()
  await page.waitForSelector('input[type=email]', { timeout: 20000 })
  ok(page.url().includes('/login'), 'after deleting the account → login screen')
  await page.fill('input[type=email]', email)
  await page.fill('input[type=password]', 'Erase-12345')
  await page.click('button[type=submit]')
  await page.waitForTimeout(1500)
  ok(page.url().includes('/login') && (await page.locator('[role=alert]').count()) > 0, 'the deleted account can no longer sign in')

  ok(errors.length === 0, 'errors: ' + (errors.join(' | ') || 'none'))
  console.log(fails ? `FAILED ${fails}` : 'ALL PASSED')
  await b.close()
})().catch((e) => { console.error('FAIL', e.message.split('\n').slice(0, 3).join(' | ')); process.exit(1) })
